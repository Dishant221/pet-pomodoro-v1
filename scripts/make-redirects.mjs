/**
 * Regenerate public/_redirects from the blog content folder.
 *
 * Posts moved from /blog/<slug>/ to /<slug>/ on 2026-08-22; every old URL
 * 301s to its new home so links and any accrued ranking survive. The list is
 * explicit per slug rather than `/blog/* → /:splat` because on Cloudflare
 * Pages redirects are evaluated before static assets — a wildcard would
 * swallow /blog/ itself, the /blog/2/ pagination pages and /blog/topic/*.
 *
 * Run after renaming or adding a redirect-worthy post:  node scripts/make-redirects.mjs
 */
import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const contentDir = path.join(root, '..', 'src', 'content', 'blog');
const outFile = path.join(root, '..', 'public', '_redirects');

const slugs = (await readdir(contentDir))
  .filter((f) => /\.(md|mdx)$/.test(f))
  .map((f) => f.replace(/\.(md|mdx)$/, ''))
  .sort();

const lines = [
  '# GENERATED by scripts/make-redirects.mjs — do not edit by hand.',
  '# Blog posts moved from /blog/<slug>/ to /<slug>/ (2026-08-22).',
  ...slugs.map((s) => `/blog/${s}/ /${s}/ 301`),
  ...slugs.map((s) => `/blog/${s} /${s}/ 301`),
  '',
];

await writeFile(outFile, lines.join('\n'));
console.log(`Wrote ${slugs.length * 2} redirects to ${outFile}`);
